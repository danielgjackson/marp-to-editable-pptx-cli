#!/usr/bin/env node
// Bundle the CLI (and the TypeScript sources it imports from the upstream
// `marp-to-editable-pptx` package) into a single CommonJS file: dist/cli.js.
//
// Upstream ships TypeScript source only (its `main` points at a webpack bundle
// that is not committed), so we compile the parts we need here. Third-party
// npm packages stay external and are resolved from node_modules at runtime.
'use strict'

const { execFileSync } = require('node:child_process')
const fs = require('node:fs')
const path = require('node:path')
const esbuild = require('esbuild')

const root = path.resolve(__dirname, '..')

// Make sure the fixes in patches/ are in the upstream sources before they are
// bundled (normally already done by postinstall; applying again is harmless).
execFileSync(process.execPath, [path.join(__dirname, 'apply-patches.js')], {
  stdio: 'inherit',
})
const upstreamDir = path.dirname(
  require.resolve('marp-to-editable-pptx/package.json', { paths: [root] }),
)
const pkg = require(path.join(root, 'package.json'))
const upstreamPkg = require(path.join(upstreamDir, 'package.json'))

// Upstream injects its DOM walker into the headless browser as a standalone
// script string. It is normally regenerated by upstream's own build step, so
// regenerate it here from dom-walker.ts (same esbuild settings as upstream's
// src/native-pptx/scripts/generate-dom-walker-script.js) rather than trusting
// the committed copy to be current.
function buildDomWalkerScript() {
  const result = esbuild.buildSync({
    entryPoints: [path.join(upstreamDir, 'src/native-pptx/dom-walker.ts')],
    bundle: true,
    format: 'iife',
    globalName: 'DomWalker',
    target: 'es2021',
    write: false,
    minify: false,
  })
  return (
    result.outputFiles[0].text +
    '\nglobalThis.extractSlides = DomWalker.extractSlides;\n'
  )
}

/** @type {import('esbuild').Plugin} */
const domWalkerPlugin = {
  name: 'dom-walker-script',
  setup(build) {
    build.onResolve({ filter: /dom-walker-script\.generated$/ }, () => ({
      path: 'dom-walker-script',
      namespace: 'dom-walker-script',
    }))
    build.onLoad({ filter: /.*/, namespace: 'dom-walker-script' }, () => ({
      contents: `export const DOM_WALKER_SCRIPT = ${JSON.stringify(buildDomWalkerScript())}`,
      loader: 'ts',
    }))
  },
}

// Everything published to npm stays external, except the upstream package,
// whose TypeScript sources must be compiled into the bundle.
/** @type {import('esbuild').Plugin} */
const externalPackagesPlugin = {
  name: 'external-packages',
  setup(build) {
    build.onResolve({ filter: /^[^./]/ }, (args) => {
      if (args.path.startsWith('marp-to-editable-pptx/')) return undefined
      return { path: args.path, external: true }
    })
  },
}

fs.rmSync(path.join(root, 'dist'), { recursive: true, force: true })

esbuild
  .build({
    absWorkingDir: root,
    entryPoints: ['src/cli.ts'],
    outfile: 'dist/cli.js',
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    sourcemap: false,
    banner: { js: '#!/usr/bin/env node' },
    define: {
      __CLI_VERSION__: JSON.stringify(pkg.version),
      __UPSTREAM_VERSION__: JSON.stringify(upstreamPkg.version),
    },
    plugins: [domWalkerPlugin, externalPackagesPlugin],
    logLevel: 'warning',
  })
  .then(() => {
    fs.chmodSync(path.join(root, 'dist/cli.js'), 0o755)
    console.log(
      `Built dist/cli.js (marp-to-editable-pptx ${upstreamPkg.version})`,
    )
  })
  .catch(() => process.exit(1))
